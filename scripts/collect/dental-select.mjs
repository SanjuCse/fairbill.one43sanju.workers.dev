// Picks values from the parsed Sabka Dentist regional price lists into src/data/sabka.js.
// Usage: node scripts/collect/dental.mjs && node scripts/collect/dental-select.mjs
import { readFileSync, writeFileSync } from "node:fs";

const raw = JSON.parse(readFileSync(new URL("../out/sabka.json", import.meta.url), "utf8"));
const out = {};
for (const [region, list] of Object.entries(raw)) {
  const p = list.map((r) => r.price);
  const n = p.length;
  const v = {
    fillingLow: p[2], fillingHigh: p[1], rct: p[3], reRct: p[4],
    crownEconomy: p[5], crownPremium: p[7], implant: p[8],
    dentureEconomy: p[9], denturePremium: p[10],
    bracesMetal: p[11], bracesCeramic: p[12], aligners: p[15],
    extractSimple: p[16], extractRoot: p[17], extractSurgical: p[19],
    cleanBasic: p[n - 3], cleanDeep: p[n - 1],
  };
  // The tables are parsed by position, so reject obviously misaligned values.
  if (v.rct < 2000 || v.rct > 6000 || v.implant < 25000 || v.implant > 40000 || v.aligners < 30000 || v.cleanBasic !== 500) throw new Error(`Sabka ${region} looks misaligned: ${JSON.stringify(v)}`);
  out[region] = v;
}
writeFileSync(new URL("../../src/data/sabka.js", import.meta.url), `// Generated by scripts/collect/dental-select.mjs from sabkadentist.com regional price lists (rupees).\nexport const SABKA_REGIONS = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).join(", "));
